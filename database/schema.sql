-- 1. DROP EXISTING TABLES (Safe teardown)
BEGIN
    FOR t IN (
        SELECT table_name FROM user_tables 
        WHERE table_name IN ('PREDICTION_LOGS', 'EXPENSES', 'INCOME', 'CATEGORIES', 'USERS')
    ) LOOP
        EXECUTE IMMEDIATE 'DROP TABLE ' || t.table_name || ' CASCADE CONSTRAINTS';
    END LOOP;
END;
/

-- 2. USERS TABLE
CREATE TABLE USERS (
    USER_ID NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    EMAIL VARCHAR2(120) NOT NULL UNIQUE,
    PASSWORD_HASH VARCHAR2(255) NOT NULL,
    FULL_NAME VARCHAR2(120) NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- Index on email
CREATE INDEX IDX_USERS_EMAIL ON USERS(EMAIL);

-- 3. CATEGORIES TABLE
CREATE TABLE CATEGORIES (
    CATEGORY_ID NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    NAME VARCHAR2(50) NOT NULL UNIQUE,
    DESCRIPTION VARCHAR2(255),
    COLOR_HEX VARCHAR2(10) DEFAULT '#2563EB',
    ICON_NAME VARCHAR2(50) DEFAULT 'Tag',
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- 4. INCOME TABLE
CREATE TABLE INCOME (
    INCOME_ID NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    USER_ID NUMBER NOT NULL,
    MONTHLY_INCOME NUMBER(14, 2) DEFAULT 0.00 NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT FK_INCOME_USER FOREIGN KEY (USER_ID) REFERENCES USERS(USER_ID) ON DELETE CASCADE,
    CONSTRAINT UQ_USER_INCOME UNIQUE (USER_ID)
);

-- 5. EXPENSES TABLE
CREATE TABLE EXPENSES (
    EXPENSE_ID NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    USER_ID NUMBER NOT NULL,
    DESCRIPTION VARCHAR2(255) NOT NULL,
    AMOUNT NUMBER(14, 2) NOT NULL,
    CATEGORY VARCHAR2(50) NOT NULL,
    PREDICTED_CATEGORY VARCHAR2(50),
    MERCHANT VARCHAR2(100),
    PAYMENT_METHOD VARCHAR2(50) DEFAULT 'UPI',
    EXPENSE_DATE DATE DEFAULT SYSDATE NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT FK_EXPENSES_USER FOREIGN KEY (USER_ID) REFERENCES USERS(USER_ID) ON DELETE CASCADE
);

-- Indexes for performance
CREATE INDEX IDX_EXPENSES_USER_DATE ON EXPENSES(USER_ID, EXPENSE_DATE);
CREATE INDEX IDX_EXPENSES_CATEGORY ON EXPENSES(CATEGORY);

-- 6. PREDICTION LOGS TABLE
CREATE TABLE PREDICTION_LOGS (
    LOG_ID NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    USER_ID NUMBER,
    INPUT_DESCRIPTION VARCHAR2(255) NOT NULL,
    INPUT_AMOUNT NUMBER(14, 2),
    PREDICTED_CATEGORY VARCHAR2(50) NOT NULL,
    CONFIDENCE NUMBER(6, 4),
    MODEL_NAME VARCHAR2(100) NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT FK_PRED_USER FOREIGN KEY (USER_ID) REFERENCES USERS(USER_ID) ON DELETE SET NULL
);

CREATE INDEX IDX_PRED_CREATED ON PREDICTION_LOGS(CREATED_AT);
